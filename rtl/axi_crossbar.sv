// Parameterized AXI4 five-channel memory-mapped crossbar (AW/W/B/AR/R).
module axi_crossbar #(
    parameter int INPUTS       = 4,
    parameter int SLAVES       = 4,
    parameter int ADDR_WIDTH   = 32,
    parameter int DATA_WIDTH   = 32,
    parameter int ID_WIDTH     = 2,
    parameter int INPUT_LIMIT  = 2,
    parameter int OUTPUT_LIMIT = 4,
    parameter int STRB_WIDTH      = DATA_WIDTH / 8,
    parameter int SOURCE_WIDTH    = INPUTS > 1 ? $clog2(INPUTS) : 1,
    parameter int OUTPUT_ID_WIDTH = ID_WIDTH + SOURCE_WIDTH
) (
    input  logic clk,
    input  logic reset_n,
    input  logic [SLAVES-1:0][ADDR_WIDTH-1:0] map_base,
    input  logic [SLAVES-1:0][ADDR_WIDTH-1:0] map_limit,
    // Write address channel
    input  logic [INPUTS-1:0]                  s_awvalid,
    output logic [INPUTS-1:0]                  s_awready,
    input  logic [INPUTS-1:0][ID_WIDTH-1:0]    s_awid,
    input  logic [INPUTS-1:0][ADDR_WIDTH-1:0]  s_awaddr,
    input  logic [INPUTS-1:0][7:0]             s_awlen,
    input  logic [INPUTS-1:0][2:0]             s_awsize,
    input  logic [INPUTS-1:0][1:0]             s_awburst,
    input  logic [INPUTS-1:0]                  s_awlock,
    input  logic [INPUTS-1:0][3:0]             s_awcache,
    input  logic [INPUTS-1:0][2:0]             s_awprot,
    input  logic [INPUTS-1:0][3:0]             s_awqos,
    // Write data channel
    input  logic [INPUTS-1:0]                  s_wvalid,
    output logic [INPUTS-1:0]                  s_wready,
    input  logic [INPUTS-1:0][DATA_WIDTH-1:0]  s_wdata,
    input  logic [INPUTS-1:0][STRB_WIDTH-1:0]  s_wstrb,
    input  logic [INPUTS-1:0]                  s_wlast,
    // Write response channel
    output logic [INPUTS-1:0]                  s_bvalid,
    input  logic [INPUTS-1:0]                  s_bready,
    output logic [INPUTS-1:0][ID_WIDTH-1:0]    s_bid,
    output logic [INPUTS-1:0][1:0]             s_bresp,
    // Read address channel
    input  logic [INPUTS-1:0]                  s_arvalid,
    output logic [INPUTS-1:0]                  s_arready,
    input  logic [INPUTS-1:0][ID_WIDTH-1:0]    s_arid,
    input  logic [INPUTS-1:0][ADDR_WIDTH-1:0]  s_araddr,
    input  logic [INPUTS-1:0][7:0]             s_arlen,
    input  logic [INPUTS-1:0][2:0]             s_arsize,
    input  logic [INPUTS-1:0][1:0]             s_arburst,
    input  logic [INPUTS-1:0]                  s_arlock,
    input  logic [INPUTS-1:0][3:0]             s_arcache,
    input  logic [INPUTS-1:0][2:0]             s_arprot,
    input  logic [INPUTS-1:0][3:0]             s_arqos,
    // Read data channel
    output logic [INPUTS-1:0]                  s_rvalid,
    input  logic [INPUTS-1:0]                  s_rready,
    output logic [INPUTS-1:0][ID_WIDTH-1:0]    s_rid,
    output logic [INPUTS-1:0][DATA_WIDTH-1:0]  s_rdata,
    output logic [INPUTS-1:0][1:0]             s_rresp,
    output logic [INPUTS-1:0]                  s_rlast,
    // Slave write address channel
    output logic [SLAVES-1:0]                  m_awvalid,
    input  logic [SLAVES-1:0]                  m_awready,
    output logic [SLAVES-1:0][OUTPUT_ID_WIDTH-1:0] m_awid,
    output logic [SLAVES-1:0][ADDR_WIDTH-1:0]  m_awaddr,
    output logic [SLAVES-1:0][7:0]             m_awlen,
    output logic [SLAVES-1:0][2:0]             m_awsize,
    output logic [SLAVES-1:0][1:0]             m_awburst,
    output logic [SLAVES-1:0]                  m_awlock,
    output logic [SLAVES-1:0][3:0]             m_awcache,
    output logic [SLAVES-1:0][2:0]             m_awprot,
    output logic [SLAVES-1:0][3:0]             m_awqos,
    // Slave write data channel
    output logic [SLAVES-1:0]                  m_wvalid,
    input  logic [SLAVES-1:0]                  m_wready,
    output logic [SLAVES-1:0][DATA_WIDTH-1:0]  m_wdata,
    output logic [SLAVES-1:0][STRB_WIDTH-1:0]  m_wstrb,
    output logic [SLAVES-1:0]                  m_wlast,
    // Slave write response channel
    input  logic [SLAVES-1:0]                  m_bvalid,
    output logic [SLAVES-1:0]                  m_bready,
    input  logic [SLAVES-1:0][OUTPUT_ID_WIDTH-1:0] m_bid,
    input  logic [SLAVES-1:0][1:0]             m_bresp,
    // Slave read address channel
    output logic [SLAVES-1:0]                  m_arvalid,
    input  logic [SLAVES-1:0]                  m_arready,
    output logic [SLAVES-1:0][OUTPUT_ID_WIDTH-1:0] m_arid,
    output logic [SLAVES-1:0][ADDR_WIDTH-1:0]  m_araddr,
    output logic [SLAVES-1:0][7:0]             m_arlen,
    output logic [SLAVES-1:0][2:0]             m_arsize,
    output logic [SLAVES-1:0][1:0]             m_arburst,
    output logic [SLAVES-1:0]                  m_arlock,
    output logic [SLAVES-1:0][3:0]             m_arcache,
    output logic [SLAVES-1:0][2:0]             m_arprot,
    output logic [SLAVES-1:0][3:0]             m_arqos,
    // Slave read data channel
    input  logic [SLAVES-1:0]                  m_rvalid,
    output logic [SLAVES-1:0]                  m_rready,
    input  logic [SLAVES-1:0][OUTPUT_ID_WIDTH-1:0] m_rid,
    input  logic [SLAVES-1:0][DATA_WIDTH-1:0]  m_rdata,
    input  logic [SLAVES-1:0][1:0]             m_rresp,
    input  logic [SLAVES-1:0]                  m_rlast
);
    axi_crossbar_write #(
        .INPUTS(INPUTS), .SLAVES(SLAVES), .ADDR_WIDTH(ADDR_WIDTH),
        .DATA_WIDTH(DATA_WIDTH), .ID_WIDTH(ID_WIDTH),
        .INPUT_LIMIT(INPUT_LIMIT), .OUTPUT_LIMIT(OUTPUT_LIMIT)
    ) write_path (
        .clk(clk), .reset_n(reset_n),
        .map_base(map_base), .map_limit(map_limit),
        .s_awvalid(s_awvalid), .s_awready(s_awready),
        .s_awid(s_awid), .s_awaddr(s_awaddr), .s_awlen(s_awlen),
        .s_awsize(s_awsize), .s_awburst(s_awburst), .s_awlock(s_awlock),
        .s_awcache(s_awcache), .s_awprot(s_awprot), .s_awqos(s_awqos),
        .s_wvalid(s_wvalid), .s_wready(s_wready),
        .s_wdata(s_wdata), .s_wstrb(s_wstrb), .s_wlast(s_wlast),
        .s_bvalid(s_bvalid), .s_bready(s_bready),
        .s_bid(s_bid), .s_bresp(s_bresp),
        .m_awvalid(m_awvalid), .m_awready(m_awready),
        .m_awid(m_awid), .m_awaddr(m_awaddr), .m_awlen(m_awlen),
        .m_awsize(m_awsize), .m_awburst(m_awburst), .m_awlock(m_awlock),
        .m_awcache(m_awcache), .m_awprot(m_awprot), .m_awqos(m_awqos),
        .m_wvalid(m_wvalid), .m_wready(m_wready),
        .m_wdata(m_wdata), .m_wstrb(m_wstrb), .m_wlast(m_wlast),
        .m_bvalid(m_bvalid), .m_bready(m_bready),
        .m_bid(m_bid), .m_bresp(m_bresp)
    );

    axi_crossbar_read #(
        .INPUTS(INPUTS), .SLAVES(SLAVES), .ADDR_WIDTH(ADDR_WIDTH),
        .DATA_WIDTH(DATA_WIDTH), .ID_WIDTH(ID_WIDTH),
        .INPUT_LIMIT(INPUT_LIMIT), .OUTPUT_LIMIT(OUTPUT_LIMIT)
    ) read_path (
        .clk(clk), .reset_n(reset_n),
        .map_base(map_base), .map_limit(map_limit),
        .s_arvalid(s_arvalid), .s_arready(s_arready),
        .s_arid(s_arid), .s_araddr(s_araddr), .s_arlen(s_arlen),
        .s_arsize(s_arsize), .s_arburst(s_arburst), .s_arlock(s_arlock),
        .s_arcache(s_arcache), .s_arprot(s_arprot), .s_arqos(s_arqos),
        .s_rvalid(s_rvalid), .s_rready(s_rready),
        .s_rid(s_rid), .s_rdata(s_rdata),
        .s_rresp(s_rresp), .s_rlast(s_rlast),
        .m_arvalid(m_arvalid), .m_arready(m_arready),
        .m_arid(m_arid), .m_araddr(m_araddr), .m_arlen(m_arlen),
        .m_arsize(m_arsize), .m_arburst(m_arburst), .m_arlock(m_arlock),
        .m_arcache(m_arcache), .m_arprot(m_arprot), .m_arqos(m_arqos),
        .m_rvalid(m_rvalid), .m_rready(m_rready),
        .m_rid(m_rid), .m_rdata(m_rdata),
        .m_rresp(m_rresp), .m_rlast(m_rlast)
    );
endmodule
